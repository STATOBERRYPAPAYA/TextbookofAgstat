checks<-list()
check<-function(label,value,expected,tol=5e-4) {
  if(length(value)!=length(expected) || any(abs(value-expected)>tol)) {
    cat('CHECK DIFFERENCE:',label,'\n');print(value);print(expected)
  }
  stopifnot(length(value)==length(expected), all(is.finite(value)),
            all(abs(value-expected)<=tol))
  checks[[length(checks)+1L]]<<-data.frame(check=label,computed=paste(signif(value,12),collapse="; "),
                                         expected=paste(expected,collapse="; "),tolerance=tol)
}
